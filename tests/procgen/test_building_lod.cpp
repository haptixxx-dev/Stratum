/**
 * A rule-generated facade reaches a third of its triangles, watertight.
 *
 * THE point of the file. A rule facade is a quilt of small open shells whose
 * boundaries do not line up, and meshopt_simplify returns 82% of level 0 on it at
 * a requested 0.5, 0.25 and 0.1 alike. The bound here is 0.35, which that
 * behaviour misses by a mile.
 *
 * A THIRD, not the tenth an earlier version of this file claimed. That tenth was
 * reached by dropping the window frames and letting the simplifier take the
 * glazing, which left 24% of the front wall see-through -- see
 * every_level_covers_the_openings_level_zero_covered, which is the test that says
 * so. The covering plane costs what it costs: twelve window frames are 96
 * triangles that cannot go while the openings are still cut.
 *
 * The number is not hard-coded against meshoptimizer: the second half runs the
 * same input with both of this file's mechanisms disabled and requires the
 * default to be strictly better. If a future meshoptimizer simplifies a quilt on
 * its own, that comparison is what says so.
 */
TEST(BuildingLod, a_rule_generated_facade_reaches_its_ratios) {
    const Mesh building = run_rule(facade_source(), 6.0, 4.0);
    const BuildingLod lod = build_building_lod(building);

    if (lod.levels.size() < 2u) {
        stratum::test::report_failure(__FILE__, __LINE__, "the facade chain has coarse levels",
                                      "chain has " + std::to_string(lod.levels.size()) +
                                          " level(s)");
        return;
    }

    const std::size_t level0 = triangle_count(lod.levels[0]);
    CHECK_TRUE(level0 > 0);

    const double coarsest =
        static_cast<double>(triangle_count(lod.levels.back())) / static_cast<double>(level0);
    if (!(coarsest <= 0.35)) {
        stratum::test::report_failure(
            __FILE__, __LINE__, "the coarsest level is at most a third of level 0",
            std::to_string(triangle_count(lod.levels.back())) + " of " + std::to_string(level0) +
                " triangles is " + std::to_string(coarsest) +
                ", which is the stall this file exists to beat");
    }

    // Monotone, non-empty, finite and well-formed at every level.
    for (std::size_t i = 1; i < lod.levels.size(); ++i) {
        CHECK_TRUE(triangle_count(lod.levels[i]) < triangle_count(lod.levels[i - 1u]));
        CHECK_TRUE(triangle_count(lod.levels[i]) > 0);
        CHECK_TRUE(mesh_is_finite(lod.levels[i]));
        CHECK_TRUE(indices_are_sane(lod.levels[i]));
        std::string reason;
        if (!submeshes_tile_exactly(lod.levels[i], reason)) {
            stratum::test::report_failure(__FILE__, __LINE__, "every level's submeshes tile",
                                          "level " + std::to_string(i) + ": " + reason);
        }
    }

    // With the detail drop and the sloppy retry both off, the same geometry goes
    // nowhere. This is the comparison that makes the bound above meaningful.
    BuildingLodConfig bare;
    bare.detail_drops.clear();
    bare.allow_sloppy = false;
    const BuildingLod stalled = build_building_lod(building, bare);

    // levels.back() IS level 0 when the bare chain has only level 0, which makes
    // stalled_ratio 1.0 and both comparisons below unconditionally true. That is
    // not a pass, it is the test going quiet: the relaxed weld failing outright
    // collapses this chain to one level, and that is one of the regressions this
    // test is here to catch rather than to skip.
    if (stalled.levels.size() < 2u) {
        stratum::test::report_failure(
            __FILE__, __LINE__, "the bare chain has a simplified level to compare",
            "the bare chain has " + std::to_string(stalled.levels.size()) +
                " level(s), so it cannot be compared and the bound above proves nothing");
        return;
    }
    const double stalled_ratio =
        static_cast<double>(triangle_count(stalled.levels.back())) / static_cast<double>(level0);
    if (!(coarsest < stalled_ratio)) {
        stratum::test::report_failure(
            __FILE__, __LINE__, "the drop and the sloppy retry are doing the work",
            "default reaches " + std::to_string(coarsest) + " and a bare chain reaches " +
                std::to_string(stalled_ratio) + ", so neither mechanism is contributing");
    }
    CHECK_TRUE(stalled_ratio > 0.5);
}

/**
 * The sloppy retry is what moves a quilt, and it is used only when it has to be.
 *
 * With the detail drops cleared there is nothing left but simplification, so the
 * retry has to fire; with the drops in place the constrained pass is never even
 * asked on this fixture, because the drop alone meets the target. Both halves
 * being asserted is what distinguishes "the retry works" from "the retry runs on
 * everything".
 */
TEST(BuildingLod, the_sloppy_retry_fires_only_when_the_constrained_pass_stalls) {
    const Mesh building = run_rule(facade_source(), 6.0, 4.0);

    BuildingLodConfig no_drops;
    no_drops.detail_drops.clear();
    const BuildingLod retried = build_building_lod(building, no_drops);
    CHECK_TRUE(retried.sloppy_levels > 0);

    BuildingLodConfig off = no_drops;
    off.allow_sloppy = false;
    const BuildingLod constrained = build_building_lod(building, off);
    CHECK_EQ(constrained.sloppy_levels, std::size_t{0});

    // The retry is kept only when it is strictly smaller than what the
    // constrained pass produced. Asserted, not guarded: a regression that
    // shortens either chain must fail this test rather than delete the one
    // cross-configuration comparison in it.
    if (retried.levels.size() < 2u || constrained.levels.size() < 2u) {
        stratum::test::report_failure(
            __FILE__, __LINE__, "both chains have a simplified level to compare",
            "retried has " + std::to_string(retried.levels.size()) + " level(s) and constrained "
            "has " + std::to_string(constrained.levels.size()) + ", so the comparison below "
            "cannot be made");
        return;
    }
    CHECK_TRUE(triangle_count(retried.levels[1]) < triangle_count(constrained.levels[1]));

    // A welded, closed tower does not need the retry: the constrained pass
    // reaches its ratios on geometry that is not a quilt.
    //
    // The tower is also where "kept only when strictly smaller" is load-bearing
    // rather than decorative. Its third ratio asks for a tenth, the constrained
    // pass stalls at 104 triangles against a target of 64 because the ground lock
    // pins the bottom two rows, so the retry DOES run -- and comes back no
    // smaller, because the same lock binds it. Keeping that result regardless
    // would put a sloppy level in a chain that has no use for one, and
    // sloppy_levels would read 1.
    BuildingLodConfig tower_cfg;
    tower_cfg.detail_drops.clear();
    const BuildingLod tower = build_building_lod(make_tower(8, 10, 12.0f, 8.0f, 20.0f, 5.0f),
                                                 tower_cfg);
    CHECK_EQ(tower.sloppy_levels, std::size_t{0});

    // FOUR levels, exactly: one per ratio, none of them dropped. Not "at least
    // three" -- that is what a chain which kept the retry's larger result and
    // then threw the level away for failing to reduce also produces, and
    // sloppy_levels cannot say so because it is only counted once a level is
    // kept. The length of the chain is where that shows.
    CHECK_EQ(tower.levels.size(), std::size_t{4});
    CHECK_EQ(tower.switch_distances.size(), std::size_t{4});
}

/**
 * The ground lock reaches meshopt_simplifySloppy, and the sloppy level it
 * produces keeps the base, the extents and the footprint.
 *
 * Nothing else in this suite constrains a sloppy level's geometry. The default
 * configuration never takes that path -- the detail drop meets its targets first
 * -- and the tower never takes it either, so the lock was only ever tested
 * against the constrained pass, which is the pass that needs it least.
 *
 * The fixture is the facade with its drops cleared, which forces the retry, and a
 * `ground_band` of 4.5 m, which is the shopfront. That is a deliberate abuse of a
 * setting meant for a base ring, and it is the only way found to get a DENSE
 * locked set and the sloppy path at the same time: the facade's actual base ring
 * is the four corners of a rectangle, and a simplifier keeps those anyway. With
 * the band the sloppy level keeps all 65 positions below 4.5 m; with it at zero
 * the same level keeps 16 of them. The second half is what makes the first mean
 * something.
 */
TEST(BuildingLod, the_ground_lock_reaches_the_sloppy_pass) {
    const Mesh building = run_rule(facade_source(), 6.0, 4.0);
    constexpr double kBand = 4.5;

    BuildingLodConfig cfg;
    cfg.detail_drops.clear();
    cfg.ground_band = static_cast<float>(kBand);
    const BuildingLod locked = build_building_lod(building, cfg);

    if (locked.levels.size() < 2u || locked.sloppy_levels == 0u) {
        stratum::test::report_failure(
            __FILE__, __LINE__, "the fixture takes the sloppy path",
            "chain has " + std::to_string(locked.levels.size()) + " level(s) and " +
                std::to_string(locked.sloppy_levels) +
                " sloppy, so nothing here constrains a sloppy level");
        return;
    }

    const std::set<PosKey> pinned = positions_below(locked.levels[0], kBand);
    CHECK_TRUE(pinned.size() >= 60u);

    const double hull0 = plan_hull_area(locked.levels[0]);
    const stratum::BoundingBox3D& reference = locked.levels[0].bounds;
    const double tolerance = 0.02 * static_cast<double>(reference.radius());

    for (std::size_t i = 1; i < locked.levels.size(); ++i) {
        const std::set<PosKey> kept = positions_below(locked.levels[i], kBand);
        for (const PosKey& position : pinned) {
            if (kept.find(position) == kept.end()) {
                stratum::test::report_failure(
                    __FILE__, __LINE__, "a locked position survives the sloppy pass",
                    "level " + std::to_string(i) + " keeps " + std::to_string(kept.size()) +
                        " of " + std::to_string(pinned.size()) + " locked positions");
                break;
            }
        }
        CHECK_NEAR(lowest_referenced_y(locked.levels[i]),
                   lowest_referenced_y(locked.levels[0]), 1e-6);

        // The extents and the footprint of a clustered level. A sloppy pass that
        // drags the ridge down or pulls a corner in changes these first.
        const stratum::BoundingBox3D& box = locked.levels[i].bounds;
        CHECK_NEAR(static_cast<double>(box.min.x), static_cast<double>(reference.min.x), tolerance);
        CHECK_NEAR(static_cast<double>(box.min.y), static_cast<double>(reference.min.y), tolerance);
        CHECK_NEAR(static_cast<double>(box.min.z), static_cast<double>(reference.min.z), tolerance);
        CHECK_NEAR(static_cast<double>(box.max.x), static_cast<double>(reference.max.x), tolerance);
        CHECK_NEAR(static_cast<double>(box.max.y), static_cast<double>(reference.max.y), tolerance);
        CHECK_NEAR(static_cast<double>(box.max.z), static_cast<double>(reference.max.z), tolerance);
        CHECK_NEAR(plan_hull_area(locked.levels[i]), hull0, hull0 * 0.03);
    }

    // Without the band the same sloppy level does NOT keep them, so the lock is
    // what is holding them and not the clusterer's own taste.
    BuildingLodConfig loose = cfg;
    loose.ground_band = 0.0f;
    const BuildingLod unlocked = build_building_lod(building, loose);
    if (unlocked.levels.size() < 2u) {
        stratum::test::report_failure(__FILE__, __LINE__,
                                      "the unlocked chain has a level to compare",
                                      "chain has " + std::to_string(unlocked.levels.size()) +
                                          " level(s)");
        return;
    }
    const std::set<PosKey> loose_kept = positions_below(unlocked.levels.back(), kBand);
    if (!(loose_kept.size() < pinned.size())) {
        stratum::test::report_failure(
            __FILE__, __LINE__, "the ground band is what pins the sloppy level",
            "with ground_band = 0 the coarsest level still keeps " +
                std::to_string(loose_kept.size()) + " of " + std::to_string(pinned.size()) +
                " positions, so the locked run above proves nothing");
    }
}

