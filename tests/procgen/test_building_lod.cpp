/**
 * Dropping the returns leaves the opening covered.
 *
 * A window is 28 triangles: 6 of reveal, 8 of frame, 2 of glazing, 12 of sill.
 * The returns -- reveal and sill -- are 18 of them and read only in raking light,
 * so they are what a coarse level sheds. What must not change is whether you can
 * see through the wall: the frame and the glazing tile the opening exactly
 * between them, and they stay.
 *
 * The measured number is the covered area of the opening, 1.2 x 2.0 = 2.4 m2,
 * before and after. It is unchanged by the drop because the reveal projects to
 * nothing through the opening -- a jamb is perpendicular to the wall -- and the
 * sill hangs below it.
 */
TEST(BuildingLod, dropping_the_returns_leaves_the_opening_covered) {
    const Mesh window = one_window();
    CHECK_TRUE(triangle_count(window) > 0);

    const double before = opening_coverage(window);
    CHECK_NEAR(before, kTileWidth * kTileHeight, 1e-6);

    const Mesh dropped = drop_detail_keys(window, first_drops());
    CHECK_NEAR(opening_coverage(dropped), kTileWidth * kTileHeight, 1e-6);

    // It really did drop something, and only what it was asked to.
    CHECK_TRUE(triangle_count(dropped) < triangle_count(window));
    CHECK_EQ(triangles_with_key(dropped, facade_material(FacadePart::Reveal)), std::size_t{0});
    CHECK_EQ(triangles_with_key(dropped, facade_material(FacadePart::Sill)), std::size_t{0});
    CHECK_EQ(triangles_with_key(dropped, facade_material(FacadePart::Glass)),
             triangles_with_key(window, facade_material(FacadePart::Glass)));
    CHECK_EQ(triangles_with_key(dropped, facade_material(FacadePart::Frame)),
             triangles_with_key(window, facade_material(FacadePart::Frame)));

    // The documented no-compaction contract: the result still addresses the input's
    // vertex array, which is what lets a lock array survive the drop.
    CHECK_EQ(dropped.vertices.size(), window.vertices.size());
    CHECK_TRUE(indices_are_sane(dropped));
}

/**
 * Dropping a covering plane is what opens a hole, and the coverage metric sees it.
 *
 * The mutation that proves the test above is not vacuous. Remove the glazing and
 * the frame instead of the reveal and the sill -- the same number of triangles,
 * near enough -- and the opening's covered area goes to zero: the wall now has a
 * hole in it that you can see the inside of the building through.
 *
 * This is also the assertion that guards the default table: a future edit that
 * adds Glass or Panel to default_facade_detail_drops() is exactly this mutation.
 */
TEST(BuildingLod, dropping_a_covering_plane_opens_a_hole) {
    const Mesh window = one_window();

    const std::vector<MaterialKey> covering = {facade_material(FacadePart::Glass),
                                               facade_material(FacadePart::Frame)};
    const Mesh holed = drop_detail_keys(window, covering);

    CHECK_TRUE(triangle_count(holed) > 0);
    CHECK_NEAR(opening_coverage(holed), 0.0, 1e-9);

    // And the default table never asks for that -- checked against
    // default_covering_plane_keys() rather than against a list written out here,
    // because the two lists disagreeing IS the defect. The table shipped with
    // DetailDrop{Frame, 1} on it while the frame was on the covering list and
    // while the comment beside it said in so many words that dropping the frame
    // "leaves a slot one frame-width wide around the glass". It did: 96 of 2400
    // rays cast at the front wall came through level 2.
    for (const DetailDrop& drop : default_facade_detail_drops()) {
        for (const MaterialKey& covering : default_covering_plane_keys()) {
            CHECK_FALSE(drop.key == covering);
        }
    }
    CHECK_TRUE(default_covering_plane_keys().size() >= 3u);
}

/**
 * NO LEVEL OF A REAL CHAIN IS SEE-THROUGH WHERE LEVEL 0 WAS SOLID.
 *
 * The test this suite did not have, and the defect it did not see. The coverage
 * metric above is correct and was only ever pointed at drop_detail_keys() on a
 * one-window fixture, so every level of the chain build_building_lod() actually
 * ships went unmeasured. Measured, the shipping chain was a colander: level 2 of
 * the default configuration had a slot around all twelve panes where the frame
 * had been dropped, and level 3 had the whole of all twelve openings open --
 * 14.4 m2 of a 6 x 10 m wall, a quarter of the front of the building, with the
 * inside visible through it.
 *
 * Asserted on EVERY level of EVERY configuration this file offers, because "the
 * drop step keeps the opening covered" was true the whole time and was not the
 * question.
 *
 * The second half is the pair that stops the first from being vacuous: with
 * covering_keys cleared the guard is off, the simplifier is free to treat an
 * opening's cover as ordinary geometry, and the chain must then produce a level
 * you CAN see through. If that ever stops being true the mechanism has stopped
 * being load-bearing, and that is worth failing over.
 */
TEST(BuildingLod, every_level_covers_the_openings_level_zero_covered) {
    const Mesh building = run_rule(facade_source(), 6.0, 4.0);

    // The fixture is the one the opening coordinates were worked out for: twelve
    // openings, all of them solid at level 0.
    const BuildingLod lod = build_building_lod(building);
    if (lod.levels.size() < 2u) {
        stratum::test::report_failure(__FILE__, __LINE__, "the facade chain has coarse levels",
                                      "chain has " + std::to_string(lod.levels.size()) +
                                          " level(s), so no level is measured here");
        return;
    }
    if (open_sample_points(lod.levels[0]) != 0) {
        stratum::test::report_failure(
            __FILE__, __LINE__, "level 0 covers all twelve openings",
            std::to_string(open_sample_points(lod.levels[0])) + " of " +
                std::to_string(kOpeningSampleTotal) +
                " sample points are open at level 0, so the coordinates are wrong and this test "
                "measures nothing");
        return;
    }

    struct Named {
        const char* what;
        BuildingLodConfig cfg;
    };
    std::vector<Named> configurations;
    configurations.push_back({"default", BuildingLodConfig{}});
    {
        BuildingLodConfig no_drops;
        no_drops.detail_drops.clear();
        configurations.push_back({"no detail drops", no_drops});
    }
    {
        BuildingLodConfig no_sloppy;
        no_sloppy.allow_sloppy = false;
        configurations.push_back({"no sloppy retry", no_sloppy});
    }
    {
        BuildingLodConfig deep;
        deep.ratios = {0.5f, 0.25f, 0.1f, 0.05f, 0.02f};
        configurations.push_back({"five ratios, down to a fiftieth", deep});
    }

    for (const Named& configuration : configurations) {
        const BuildingLod chain = build_building_lod(building, configuration.cfg);
        for (std::size_t i = 0; i < chain.levels.size(); ++i) {
            const int open = open_sample_points(chain.levels[i]);
            if (open != 0) {
                stratum::test::report_failure(
                    __FILE__, __LINE__, "no level is see-through where level 0 was solid",
                    std::string(configuration.what) + " level " + std::to_string(i) + " (" +
                        std::to_string(triangle_count(chain.levels[i])) + " triangles) leaves " +
                        std::to_string(open) + " of " + std::to_string(kOpeningSampleTotal) +
                        " sample points of the twelve openings open");
            }
        }
    }

    // The pair. With the covering planes unguarded the simplifier opens them, so
    // the runs above are testing a mechanism rather than a coincidence.
    BuildingLodConfig unguarded;
    unguarded.covering_keys.clear();
    const BuildingLod holed = build_building_lod(building, unguarded);
    int worst = 0;
    for (const Mesh& level : holed.levels) {
        worst = std::max(worst, open_sample_points(level));
    }
    if (worst == 0) {
        stratum::test::report_failure(
            __FILE__, __LINE__, "the covering guard is what keeps the openings covered",
            "with covering_keys cleared the chain still covers every opening at every one of its " +
                std::to_string(holed.levels.size()) +
                " levels, so the guarded runs above prove nothing");
    }
}

/**
 * A detail drop that names a covering plane is refused, not honoured quietly.
 *
 * The exact shape of the defect that shipped: default_facade_detail_drops()
 * carried DetailDrop{Frame, 1}, the frame is half of a window's cover, and the
 * chain emitted a level with a slot around every pane. Putting that row back is
 * the mutation, and the chain must lose the levels at and past its ratio rather
 * than emit them.
 */
TEST(BuildingLod, a_drop_that_names_a_covering_plane_costs_its_levels) {
    const Mesh building = run_rule(facade_source(), 6.0, 4.0);

    const BuildingLod sound = build_building_lod(building);
    if (sound.levels.size() < 3u) {
        stratum::test::report_failure(__FILE__, __LINE__, "the default chain has three levels",
                                      "chain has " + std::to_string(sound.levels.size()) +
                                          " level(s), so there is nothing to lose");
        return;
    }

    BuildingLodConfig reinstated;
    reinstated.detail_drops.push_back(DetailDrop{facade_material(FacadePart::Frame), 1u});
    const BuildingLod shortened = build_building_lod(building, reinstated);

    CHECK_TRUE(shortened.levels.size() < sound.levels.size());
    CHECK_EQ(shortened.levels.size(), shortened.switch_distances.size());
    for (std::size_t i = 0; i < shortened.levels.size(); ++i) {
        CHECK_EQ(open_sample_points(shortened.levels[i]), 0);
    }
}

/**
 * The glazing keeps its own material on the level it survives.
 *
 * Re-attribution after a whole-mesh simplify hands each triangle the key its
 * vertices agree on, and on a facade that rule alone is wrong: the glazing sits
 * INSIDE its frame, so all four of its corners are frame vertices too and the
 * vote gives every glazing triangle to the frame. The window then renders as
 * stone. Measured before the fix, all 24 glazing triangles of this fixture were
 * attributed to the frame on a level where the simplifier had not touched a
 * single triangle.
 *
 * So the first simplified level must still carry exactly the glazing level 0
 * carried.
 */
TEST(BuildingLod, the_glazing_keeps_its_material_where_it_survives) {
    const Mesh building = run_rule(facade_source(), 6.0, 4.0);
    const BuildingLod lod = build_building_lod(building);
    if (lod.levels.size() < 2u) {
        stratum::test::report_failure(__FILE__, __LINE__, "the chain has a simplified level",
                                      "chain has " + std::to_string(lod.levels.size()) +
                                          " level(s), so the glazing is never re-attributed here");
        return;
    }

    const MaterialKey glass = facade_material(FacadePart::Glass);
    const std::size_t at_level0 = triangles_with_key(lod.levels[0], glass);
    CHECK_TRUE(at_level0 > 0);
    CHECK_EQ(triangles_with_key(lod.levels[1], glass), at_level0);

    // The returns are gone from the same level, which is what paid for it.
    CHECK_EQ(triangles_with_key(lod.levels[1], facade_material(FacadePart::Reveal)),
             std::size_t{0});
    CHECK_EQ(triangles_with_key(lod.levels[1], facade_material(FacadePart::Sill)), std::size_t{0});
}

/// A key named in the drops is absent from the levels it names, and only those
TEST(BuildingLod, a_detail_drop_is_keyed_on_the_ratio_and_not_on_the_finished_level) {
    const Mesh building = run_rule(facade_source(), 6.0, 4.0);

    BuildingLodConfig cfg;
    cfg.ratios = {0.9f, 0.5f, 0.1f};
    cfg.detail_drops = {DetailDrop{facade_material(FacadePart::Sill), 1u}};

    const BuildingLod lod = build_building_lod(building, cfg);
    if (lod.levels.size() < 2u) {
        stratum::test::report_failure(__FILE__, __LINE__, "the chain has a simplified level",
                                      "chain has " + std::to_string(lod.levels.size()) +
                                          " level(s), so no drop is ever applied here");
        return;
    }

    const MaterialKey sill = facade_material(FacadePart::Sill);
    CHECK_TRUE(triangles_with_key(lod.levels[0], sill) > 0);

    // ratios[0] is 0.9, which is inside kMinLevelReduction of level 0 and is
    // therefore dropped -- so the first SURVIVING simplified level is the one
    // built from ratios[1], and the sill is gone from it. Had the drop been keyed
    // on the finished level index, that dropped candidate would have shifted the
    // sill onto a level nobody asked for.
    for (std::size_t i = 1; i < lod.levels.size(); ++i) {
        CHECK_EQ(triangles_with_key(lod.levels[i], sill), std::size_t{0});
    }
}

