/**
 * @brief Run a rule file over a footprint and return what it generated
 *
 * The parse is asserted as a rendered string rather than as a boolean, so a
 * fixture whose rule text has a typo prints the parser's own caret diagnostic
 * instead of "0 != 400".
 */
[[nodiscard]] Mesh run_rule(const std::string& source, double width, double depth) {
    namespace rules = stratum::procgen::rules;
    const rules::ParseResult parsed = rules::parse(source, "building_lod_test.srl");
    CHECK_EQ(parsed.render_all(source), std::string{});
    const rules::GenerationResult result = rules::generate(
        parsed.file, rules::shape_from_rect(width, depth), {}, &rules::full_operations());
    CHECK_TRUE(result.ok());
    return result.build_mesh();
}

/**
 * @brief The E6 proof: a whole building from the rule language
 *
 * `extrude` raises the mass, `roof` puts a 35 degree gable on it, `select face`
 * picks the front, two `split`s cut it into floors and bays, and `window()`
 * glazes every middle bay. Three floors of four bays is twelve windows, and a
 * window is 28 triangles of which 26 are reveal, sill and frame.
 */
[[nodiscard]] std::string facade_source() {
    return "@start\n"
           "rule Main {\n"
           "    set(\"wall_thickness\", 0.4);\n"
           "    extrude(10.0);\n"
           "    roof(\"gable\", 35.0);\n"
           "    select face {\n"
           "        front : { Facade(); }\n"
           "        all   : { Shell(); }\n"
           "    }\n"
           "}\n"
           "rule Shell { }\n"
           "rule Facade {\n"
           "    split(y) {\n"
           "        4.0 : { Shopfront(); }\n"
           "        repeat { 2.0 : { UpperFloor(); } }\n"
           "    }\n"
           "}\n"
           "rule UpperFloor { split(x) { repeat { 1.5 : { Bay(); } } } }\n"
           "rule Bay {\n"
           "    split(x) {\n"
           "        0.4 : { Pier(); }\n"
           "        0.6 : { Window(); }\n"
           "        ~1.0 : { Pier(); }\n"
           "    }\n"
           "}\n"
           "rule Shopfront { wall_panel(); }\n"
           "rule Pier { wall_panel(); }\n"
           "rule Window { window(); }\n";
}

/// One glazed tile, 1.2 m by 2.0 m, in a 0.4 m wall
[[nodiscard]] Mesh one_window() {
    return run_rule("@start\nrule Main { set(\"wall_thickness\", 0.4); window(); }\n", 1.2, 2.0);
}

/// The opening one_window() glazes, in the plane the tile was built in
constexpr double kTileWidth = 1.2;
constexpr double kTileHeight = 2.0;

/**
 * @brief Area of the opening that geometry still covers, seen through the wall
 *
 * The tile lies in the xz plane and the wall's outward normal is -y, so the view
 * through the opening is the projection that drops y. A triangle counts when its
 * centroid projects strictly inside the opening, which excludes the sill -- it
 * hangs below the tile -- and gives the reveal an area of zero, because a jamb is
 * perpendicular to the wall and projects to a line.
 *
 * A fully covered opening therefore measures exactly kTileWidth * kTileHeight
 * whether or not the reveal and the sill are there, and an opening with the
 * glazing removed measures zero. That is the whole point: the number answers "can
 * you see through the wall", not "how much geometry is left".
 */
[[nodiscard]] double opening_coverage(const Mesh& mesh) {
    double total = 0.0;
    for (std::size_t t = 0; t + 2u < mesh.indices.size(); t += 3u) {
        const glm::vec3& a = mesh.vertices[mesh.indices[t]].position;
        const glm::vec3& b = mesh.vertices[mesh.indices[t + 1u]].position;
        const glm::vec3& c = mesh.vertices[mesh.indices[t + 2u]].position;
        const double cx = (static_cast<double>(a.x) + b.x + c.x) / 3.0;
        const double cz = (static_cast<double>(a.z) + b.z + c.z) / 3.0;
        constexpr double kInside = 1.0e-6;
        if (cx <= kInside || cx >= kTileWidth - kInside || cz <= kInside ||
            cz >= kTileHeight - kInside) {
            continue;
        }
        const double area = 0.5 * std::fabs(static_cast<double>(b.x - a.x) * (c.z - a.z) -
                                            static_cast<double>(c.x - a.x) * (b.z - a.z));
        total += area;
    }
    return total;
}

