/**
 * Level 0 carries every triangle of the input, including the ones no SubMesh
 * range claims.
 *
 * This is the roof test. GenerationResult::build_mesh() opens no range for a
 * terminal whose faces are all MaterialId::Default, so those triangles sit in a
 * GAP between two ranges -- 14 of the facade fixture's 400, which are the roof and
 * the three unglazed walls. An implementation that walks effective_submeshes()
 * and copies what it finds deletes the roof off the building and reports nothing.
 *
 * Asserted as a multiset of content-addressed triangles, so reordering the index
 * buffer, renumbering the vertices and coalescing the ranges are all allowed and
 * losing one triangle is not.
 */
TEST(BuildingLod, level_zero_keeps_every_triangle_including_the_ones_no_range_claims) {
    const Mesh building = run_rule(facade_source(), 6.0, 4.0);
    CHECK_TRUE(triangle_count(building) > 300);

    // The fixture really does have the gap this test is about; without it the
    // test would pass for the wrong reason.
    const std::size_t claimed = claimed_triangles(building);
    CHECK_TRUE(claimed < triangle_count(building));

    const BuildingLod lod = build_building_lod(building);
    if (lod.levels.empty()) {
        stratum::test::report_failure(__FILE__, __LINE__, "the chain has a level 0",
                                      "build_building_lod returned nothing");
        return;
    }

    const Mesh& level0 = lod.levels[0];
    CHECK_EQ(triangle_count(level0), triangle_count(building));

    // Level 0 is NEVER WELDED, and a triangle multiset cannot say so -- a weld
    // moves no triangle and loses none, it only merges the vertices behind them.
    // The vertex count is the one number that can tell them apart: the relaxed
    // weld this file builds its simplification base with takes this fixture from
    // 802 vertices to 592, and shipping that as level 0 would close every UV seam
    // on the mesh the player stands in front of.
    CHECK_EQ(level0.vertices.size(), building.vertices.size());

    // Same multiset of triangles, same windings. Reordering, renumbering and
    // range coalescing are all allowed; losing one triangle is not.
    const std::multiset<std::array<PosKey, 3>> before = triangle_multiset(building);
    const std::multiset<std::array<PosKey, 3>> after = triangle_multiset(level0);
    CHECK_EQ(after.size(), triangle_count(building));
    CHECK_TRUE(before == after);

    // The unclaimed triangles arrive under the Default slot, which is what
    // Mesh::sort_submeshes_by_material() promises for the same case, and level 0
    // claims all of its own.
    CHECK_EQ(claimed_triangles(level0), triangle_count(level0));
    CHECK_EQ(triangles_with_key(level0, MaterialKey{MaterialId::Default, 0u}),
             triangle_count(building) - claimed);
}

/// Level 0 states each material once, ascending, with the ranges tiling exactly
TEST(BuildingLod, level_zero_coalesces_the_ranges_to_one_per_material) {
    const Mesh building = run_rule(facade_source(), 6.0, 4.0);

    // The rule mesh appends one range per terminal, so there are far more ranges
    // than materials before the chain touches it.
    CHECK_TRUE(building.submeshes.size() > 20);

    const BuildingLod lod = build_building_lod(building);
    if (lod.levels.empty()) {
        stratum::test::report_failure(__FILE__, __LINE__, "the chain has a level 0",
                                      "build_building_lod returned nothing");
        return;
    }

    const Mesh& level0 = lod.levels[0];
    std::string reason;
    if (!submeshes_tile_exactly(level0, reason)) {
        stratum::test::report_failure(__FILE__, __LINE__, "level 0 submeshes tile", reason);
    }

    // One range per distinct key the input carried, plus the Default slot the
    // unclaimed triangles land in.
    const bool has_gap = claimed_triangles(building) < triangle_count(building);
    std::vector<uint32_t> expected = keys_of(building);
    if (has_gap) {
        expected.push_back(MaterialKey{MaterialId::Default, 0u}.packed());
        std::sort(expected.begin(), expected.end());
        expected.erase(std::unique(expected.begin(), expected.end()), expected.end());
    }
    CHECK_EQ(level0.submeshes.size(), expected.size());

    // Ascending by packed key, which is what makes the layout a function of the
    // input rather than of the order the terminals happened to be appended in.
    for (std::size_t i = 1; i < level0.submeshes.size(); ++i) {
        const MaterialKey previous{level0.submeshes[i - 1u].material,
                                   level0.submeshes[i - 1u].variant};
        const MaterialKey current{level0.submeshes[i].material, level0.submeshes[i].variant};
        CHECK((previous.packed()) < (current.packed()));
    }
}

