/// Lowest y any TRIANGLE of the mesh reaches, ignoring vertices nothing references
[[nodiscard]] double lowest_referenced_y(const Mesh& mesh) {
    double lowest = 1.0e30;
    for (const uint32_t index : mesh.indices) {
        if (index < mesh.vertices.size()) {
            lowest = std::min(lowest, static_cast<double>(mesh.vertices[index].position.y));
        }
    }
    return lowest;
}

/**
 * @brief Distinct referenced positions within @p band of @p floor
 *
 * Walks the INDEX buffer. A simplifier may leave a vertex in the buffer that no
 * triangle names any more, and counting those would report a base ring that never
 * shrinks however much of it was collapsed -- a test that cannot fail.
 */
[[nodiscard]] std::set<PosKey> base_positions(const Mesh& mesh, double floor, double band) {
    std::set<PosKey> out;
    for (const uint32_t index : mesh.indices) {
        if (index >= mesh.vertices.size()) {
            continue;
        }
        const glm::vec3& p = mesh.vertices[index].position;
        if (static_cast<double>(p.y) <= floor + band) {
            out.insert(pos_key(p));
        }
    }
    return out;
}

