/**
 * Every position of the base ring survives at every level, and the ground band is
 * what makes that true.
 *
 * A building whose base moves floats above the terrain or sinks into it, and that
 * reads from much further away than the detail the level traded for it.
 *
 * The second half is the part that stops the first from being vacuous. With
 * `ground_band` at zero the same call loses base positions outright -- measured
 * on this fixture the coarsest level's lowest vertex rises from y = 0 to y = 2 m,
 * taking the whole building off the ground. If that ever stops being true, this
 * test fails and the lock has stopped being load-bearing; that is a fact worth
 * finding out about rather than a bound to relax.
 */
TEST(BuildingLod, the_base_ring_survives_every_level) {
    const Mesh tower = make_tower(8, 10, 12.0f, 8.0f, 20.0f, 5.0f);

    BuildingLodConfig cfg;
    cfg.detail_drops.clear(); // no facade materials here; keep the question to the lock
    const BuildingLod locked = build_building_lod(tower, cfg);
    if (locked.levels.size() < 2u) {
        stratum::test::report_failure(__FILE__, __LINE__, "the tower produced a simplified level",
                                      "chain has " + std::to_string(locked.levels.size()) +
                                          " level(s)");
        return;
    }

    const double floor = lowest_referenced_y(locked.levels[0]);
    const std::set<PosKey> ring = base_positions(locked.levels[0], floor, 0.05);
    CHECK_TRUE(ring.size() >= 32u);

    for (std::size_t i = 1; i < locked.levels.size(); ++i) {
        const std::set<PosKey> kept = base_positions(locked.levels[i], floor, 0.05);
        if (kept.size() != ring.size()) {
            stratum::test::report_failure(
                __FILE__, __LINE__, "every base position survives",
                "level " + std::to_string(i) + " keeps " + std::to_string(kept.size()) + " of " +
                    std::to_string(ring.size()) + " base positions");
        }
        for (const PosKey& position : ring) {
            CHECK_TRUE(kept.find(position) != kept.end());
        }
        CHECK_NEAR(lowest_referenced_y(locked.levels[i]), floor, 1e-6);
    }

    // The same chain with the lock switched off does NOT keep the ground.
    BuildingLodConfig loose = cfg;
    loose.ground_band = 0.0f;
    const BuildingLod unlocked = build_building_lod(tower, loose);
    if (unlocked.levels.size() < 2u) {
        stratum::test::report_failure(
            __FILE__, __LINE__, "the unlocked chain has a simplified level to compare",
            "with ground_band = 0 the chain has " + std::to_string(unlocked.levels.size()) +
                " level(s), so the locked run above proves nothing");
        return;
    }

    const std::set<PosKey> coarse =
        base_positions(unlocked.levels.back(), floor, 0.05);
    if (!(coarse.size() < ring.size())) {
        stratum::test::report_failure(
            __FILE__, __LINE__, "the ground band is what keeps the base ring",
            "with ground_band = 0 the coarsest level still keeps " +
                std::to_string(coarse.size()) + " of " + std::to_string(ring.size()) +
                " base positions, so the locked run above proves nothing");
    }
}

