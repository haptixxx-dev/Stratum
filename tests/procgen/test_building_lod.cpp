[[nodiscard]] std::size_t triangle_count(const Mesh& mesh) {
    return mesh.indices.size() / 3u;
}

/// Quantised position, so a vertex can be compared across a pass that renumbers
using PosKey = std::array<int64_t, 3>;

[[nodiscard]] PosKey pos_key(const glm::vec3& p) {
    const auto q = [](float v) { return static_cast<int64_t>(std::llround(v * 1.0e4f)); };
    return PosKey{q(p.x), q(p.y), q(p.z)};
}

/**
 * @brief A mesh reduced to a multiset of canonical position triples
 *
 * Content-addressed and material-blind, because this is the instrument for "is
 * this still the same geometry" and the material rule is a separate question with
 * its own tests. Every triangle of the index buffer is walked, whether or not a
 * SubMesh range claims it -- counting only the claimed ones is precisely the bug
 * this is the instrument for.
 *
 * The corner order is rotated to its smallest member rather than sorted, so a
 * triangle with the winding reversed does NOT compare equal to the original: a
 * level that flipped its normals is a different level.
 */
[[nodiscard]] std::multiset<std::array<PosKey, 3>> triangle_multiset(const Mesh& mesh) {
    std::multiset<std::array<PosKey, 3>> out;
    for (std::size_t t = 0; t + 2u < mesh.indices.size(); t += 3u) {
        if (mesh.indices[t] >= mesh.vertices.size() ||
            mesh.indices[t + 1u] >= mesh.vertices.size() ||
            mesh.indices[t + 2u] >= mesh.vertices.size()) {
            continue;
        }
        PosKey a = pos_key(mesh.vertices[mesh.indices[t]].position);
        PosKey b = pos_key(mesh.vertices[mesh.indices[t + 1u]].position);
        PosKey c = pos_key(mesh.vertices[mesh.indices[t + 2u]].position);
        // Rotate to the smallest corner, keeping the cycle.
        if (b < a && b < c) {
            std::swap(a, b);
            std::swap(b, c);
        } else if (c < a && c < b) {
            std::swap(b, c);
            std::swap(a, b);
        }
        out.insert(std::array<PosKey, 3>{a, b, c});
    }
    return out;
}

/// Triangles of @p mesh that some SubMesh range claims, which need not be all of them
[[nodiscard]] std::size_t claimed_triangles(const Mesh& mesh) {
    std::size_t claimed = 0;
    for (const SubMesh& sub : mesh.effective_submeshes()) {
        claimed += sub.index_count / 3u;
    }
    return claimed;
}

/// Every index addresses a vertex, and the index count is a whole number of triangles
[[nodiscard]] bool indices_are_sane(const Mesh& mesh) {
    if ((mesh.indices.size() % 3u) != 0u) {
        return false;
    }
    for (const uint32_t index : mesh.indices) {
        if (index >= mesh.vertices.size()) {
            return false;
        }
    }
    return true;
}

/// No NaN, no infinity, anywhere in the positions
[[nodiscard]] bool mesh_is_finite(const Mesh& mesh) {
    for (const Vertex& v : mesh.vertices) {
        if (!std::isfinite(v.position.x) || !std::isfinite(v.position.y) ||
            !std::isfinite(v.position.z)) {
            return false;
        }
    }
    return true;
}

/**
 * @brief The ranges tile the index buffer with no gap, no overlap and no repeat
 *
 * A gap is the failure that ate the roof, so it is checked here on every level
 * rather than only on the input.
 */
[[nodiscard]] bool submeshes_tile_exactly(const Mesh& mesh, std::string& reason) {
    const std::vector<SubMesh> ranges = mesh.effective_submeshes();
    std::set<uint32_t> keys;
    uint32_t cursor = 0;
    for (const SubMesh& sub : ranges) {
        if (sub.index_offset != cursor) {
            reason = "range at " + std::to_string(sub.index_offset) + " should start at " +
                     std::to_string(cursor);
            return false;
        }
        if ((sub.index_count % 3u) != 0u || sub.index_count == 0u) {
            reason = "range at " + std::to_string(sub.index_offset) + " holds " +
                     std::to_string(sub.index_count) + " indices";
            return false;
        }
        const MaterialKey key{sub.material, sub.variant};
        if (!keys.insert(key.packed()).second) {
            reason = "material " + std::string(stratum::material_id_name(sub.material)) +
                     " appears in two ranges";
            return false;
        }
        cursor += sub.index_count;
    }
    if (cursor != mesh.indices.size()) {
        reason = "ranges cover " + std::to_string(cursor) + " of " +
                 std::to_string(mesh.indices.size()) + " indices";
        return false;
    }
    return true;
}

/// The material keys a mesh carries, ascending
[[nodiscard]] std::vector<uint32_t> keys_of(const Mesh& mesh) {
    std::vector<uint32_t> keys;
    for (const SubMesh& sub : mesh.effective_submeshes()) {
        keys.push_back(MaterialKey{sub.material, sub.variant}.packed());
    }
    std::sort(keys.begin(), keys.end());
    keys.erase(std::unique(keys.begin(), keys.end()), keys.end());
    return keys;
}

/// Triangles carrying one material key
[[nodiscard]] std::size_t triangles_with_key(const Mesh& mesh, MaterialKey key) {
    std::size_t count = 0;
    for (const SubMesh& sub : mesh.effective_submeshes()) {
        if (sub.material == key.material && sub.variant == key.variant) {
            count += sub.index_count / 3u;
        }
    }
    return count;
}

/// Two meshes agree on every field a cache would hash
[[nodiscard]] bool meshes_are_identical(const Mesh& a, const Mesh& b) {
    if (a.vertices.size() != b.vertices.size()) return false;
    if (a.indices.size() != b.indices.size()) return false;
    if (a.submeshes.size() != b.submeshes.size()) return false;
    for (std::size_t i = 0; i < a.vertices.size(); ++i) {
        if (!(a.vertices[i] == b.vertices[i])) return false;
    }
    for (std::size_t i = 0; i < a.indices.size(); ++i) {
        if (a.indices[i] != b.indices[i]) return false;
    }
    for (std::size_t i = 0; i < a.submeshes.size(); ++i) {
        if (a.submeshes[i].index_offset != b.submeshes[i].index_offset) return false;
        if (a.submeshes[i].index_count != b.submeshes[i].index_count) return false;
        if (a.submeshes[i].material != b.submeshes[i].material) return false;
        if (a.submeshes[i].variant != b.submeshes[i].variant) return false;
    }
    return true;
}

