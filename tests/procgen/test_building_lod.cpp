/**
 * Two runs over the same input produce identical chains.
 *
 * A building's chain is built off the main thread and cached, and a level that
 * varies run to run poisons the cache. Compared field by field rather than by a
 * dump, because a dump that summarises is a dump that can miss what changed.
 */
TEST(BuildingLod, the_chain_is_deterministic) {
    const Mesh building = run_rule(facade_source(), 6.0, 4.0);

    const BuildingLod first = build_building_lod(building);
    const BuildingLod second = build_building_lod(building);

    // Not vacuous: every assertion below is an equality between two runs, and an
    // implementation that always returned an empty chain would satisfy all of
    // them. There has to be something to compare before comparing it means
    // anything.
    if (first.levels.size() < 3u) {
        stratum::test::report_failure(__FILE__, __LINE__, "there is a chain to compare",
                                      "the chain has " + std::to_string(first.levels.size()) +
                                          " level(s), so comparing two runs of it proves little");
        return;
    }
    for (const Mesh& level : first.levels) {
        CHECK_TRUE(triangle_count(level) > 0);
    }

    CHECK_EQ(first.levels.size(), second.levels.size());
    CHECK_EQ(first.switch_distances.size(), second.switch_distances.size());
    CHECK_EQ(first.sloppy_levels, second.sloppy_levels);
    if (first.levels.size() != second.levels.size()) return;

    for (std::size_t i = 0; i < first.levels.size(); ++i) {
        if (!meshes_are_identical(first.levels[i], second.levels[i])) {
            stratum::test::report_failure(__FILE__, __LINE__, "levels are identical across runs",
                                          "level " + std::to_string(i) + " differs");
        }
        CHECK_NEAR(static_cast<double>(first.switch_distances[i]),
                   static_cast<double>(second.switch_distances[i]), 1e-9);
    }
}

/**
 * The chain holds its shape: the bounding box of every level is level 0's.
 *
 * Not a silhouette proof on its own -- a box survives deleting everything but the
 * corners -- which is why it is asserted alongside the base-ring and coverage
 * tests rather than instead of them. What it does catch is the failure mode the
 * sloppy pass can have: a clusterer that drags the ridge down or pulls a corner
 * in changes these numbers first.
 */
TEST(BuildingLod, every_level_keeps_the_extents_of_level_zero) {
    const Mesh building = run_rule(facade_source(), 6.0, 4.0);

    // Both configurations, because the DEFAULT one never takes the sloppy path --
    // the detail drop meets its targets first -- and the clusterer is the thing
    // an extents test is for. Running only the default leaves the failure mode
    // named in this comment unwatched.
    BuildingLodConfig no_drops;
    no_drops.detail_drops.clear();

    const BuildingLod chains[2] = {build_building_lod(building),
                                   build_building_lod(building, no_drops)};
    CHECK_TRUE(chains[1].sloppy_levels > 0);

    for (const BuildingLod& lod : chains) {
        if (lod.levels.size() < 2u) {
            stratum::test::report_failure(__FILE__, __LINE__, "the chain has a coarse level",
                                          "chain has " + std::to_string(lod.levels.size()) +
                                              " level(s), so no extents are compared");
            continue;
        }
        const stratum::BoundingBox3D& reference = lod.levels[0].bounds;
        const double tolerance = 0.02 * static_cast<double>(reference.radius());
        const double hull = plan_hull_area(lod.levels[0]);

        for (std::size_t i = 1; i < lod.levels.size(); ++i) {
            const stratum::BoundingBox3D& box = lod.levels[i].bounds;
            CHECK_NEAR(static_cast<double>(box.min.x), static_cast<double>(reference.min.x),
                       tolerance);
            CHECK_NEAR(static_cast<double>(box.min.y), static_cast<double>(reference.min.y),
                       tolerance);
            CHECK_NEAR(static_cast<double>(box.min.z), static_cast<double>(reference.min.z),
                       tolerance);
            CHECK_NEAR(static_cast<double>(box.max.x), static_cast<double>(reference.max.x),
                       tolerance);
            CHECK_NEAR(static_cast<double>(box.max.y), static_cast<double>(reference.max.y),
                       tolerance);
            CHECK_NEAR(static_cast<double>(box.max.z), static_cast<double>(reference.max.z),
                       tolerance);

            // A box is blind to a corner cut off at 45 degrees and to a wall that
            // has holes in it. The hull catches the first; see
            // every_level_covers_the_openings_level_zero_covered for the second.
            CHECK_NEAR(plan_hull_area(lod.levels[i]), hull, hull * 0.03);
        }
    }
}
