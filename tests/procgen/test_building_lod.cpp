/**
 * @brief True when a +z ray at (@p x, @p y) meets some triangle at or beyond @p z_min
 *
 * The instrument for the question the whole file turns on: standing in front of
 * the building and looking at this point, is there anything there.
 *
 * DELIBERATELY INDEPENDENT of how build_building_lod() decides the same thing.
 * The implementation shoots one ray per covering triangle of level 0 along that
 * triangle's own normal; this walks a grid in world coordinates that were worked
 * out by hand from the rule file. A test that re-ran the implementation's own
 * measurement could only ever agree with it.
 *
 * The @p z_min floor excludes the BACK wall of the building, which a ray through
 * a hole in the front wall would otherwise hit -- and hitting the back wall
 * through a hole is exactly the failure being looked for, not the absence of one.
 */
[[nodiscard]] bool front_wall_is_solid_at(const Mesh& mesh, double x, double y, double z_min) {
    for (std::size_t t = 0; t + 2u < mesh.indices.size(); t += 3u) {
        if (mesh.indices[t] >= mesh.vertices.size() ||
            mesh.indices[t + 1u] >= mesh.vertices.size() ||
            mesh.indices[t + 2u] >= mesh.vertices.size()) {
            continue;
        }
        const glm::vec3& a = mesh.vertices[mesh.indices[t]].position;
        const glm::vec3& b = mesh.vertices[mesh.indices[t + 1u]].position;
        const glm::vec3& c = mesh.vertices[mesh.indices[t + 2u]].position;

        // Barycentric coordinates of (x, y) in the triangle's xy projection. A
        // triangle edge-on to the wall has a zero determinant and covers nothing.
        const double det = static_cast<double>(b.y - c.y) * (a.x - c.x) +
                           static_cast<double>(c.x - b.x) * (a.y - c.y);
        if (std::fabs(det) < 1.0e-12) {
            continue;
        }
        const double l1 = (static_cast<double>(b.y - c.y) * (x - c.x) +
                           static_cast<double>(c.x - b.x) * (y - c.y)) /
                          det;
        const double l2 = (static_cast<double>(c.y - a.y) * (x - c.x) +
                           static_cast<double>(a.x - c.x) * (y - c.y)) /
                          det;
        const double l3 = 1.0 - l1 - l2;
        if (l1 < -1.0e-9 || l2 < -1.0e-9 || l3 < -1.0e-9) {
            continue;
        }
        if (l1 * a.z + l2 * b.z + l3 * c.z >= z_min) {
            return true;
        }
    }
    return false;
}

/// Sample points per opening, per axis. 25 rays per opening, 300 for the facade.
constexpr int kOpeningSamples = 5;

/**
 * @brief How many of the twelve openings' sample points you can see through
 *
 * Counted rather than measured as an area because a count needs no projection
 * basis and no winding, and because the answer that matters is binary per point.
 *
 * @param mesh Any level of a chain built from facade_source() at 6 x 4 m
 * @return Open sample points, out of 12 * kOpeningSamples^2
 */
[[nodiscard]] int open_sample_points(const Mesh& mesh) {
    int open = 0;
    for (const double cx : kOpeningCentresX) {
        for (const double cy : kOpeningCentresY) {
            for (int r = 0; r < kOpeningSamples; ++r) {
                for (int c = 0; c < kOpeningSamples; ++c) {
                    const double x = cx - kOpeningWidth * 0.5 +
                                     kOpeningWidth * (c + 0.5) / kOpeningSamples;
                    const double y = cy - kOpeningHeight * 0.5 +
                                     kOpeningHeight * (r + 0.5) / kOpeningSamples;
                    if (!front_wall_is_solid_at(mesh, x, y, kFrontWallZ)) {
                        ++open;
                    }
                }
            }
        }
    }
    return open;
}

/// Every sample point of every opening
constexpr int kOpeningSampleTotal = 12 * kOpeningSamples * kOpeningSamples;

/// Distinct referenced positions at or below @p ceiling metres
[[nodiscard]] std::set<PosKey> positions_below(const Mesh& mesh, double ceiling) {
    std::set<PosKey> out;
    for (const uint32_t index : mesh.indices) {
        if (index < mesh.vertices.size() &&
            static_cast<double>(mesh.vertices[index].position.y) <= ceiling) {
            out.insert(pos_key(mesh.vertices[index].position));
        }
    }
    return out;
}

/**
 * @brief Area of the convex hull of the referenced positions in plan
 *
 * The footprint a player sees from above, and the thing a clusterer pulls a
 * corner in on. A bounding box cannot see a corner cut off at 45 degrees; a hull
 * can.
 */
[[nodiscard]] double plan_hull_area(const Mesh& mesh) {
    std::vector<std::array<double, 2>> points;
    for (const uint32_t index : mesh.indices) {
        if (index < mesh.vertices.size()) {
            points.push_back({static_cast<double>(mesh.vertices[index].position.x),
                              static_cast<double>(mesh.vertices[index].position.z)});
        }
    }
    std::sort(points.begin(), points.end());
    points.erase(std::unique(points.begin(), points.end()), points.end());
    if (points.size() < 3u) {
        return 0.0;
    }
    const auto cross = [](const std::array<double, 2>& o, const std::array<double, 2>& a,
                          const std::array<double, 2>& b) {
        return (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0]);
    };
    std::vector<std::array<double, 2>> hull(points.size() * 2u);
    std::size_t k = 0;
    for (std::size_t i = 0; i < points.size(); ++i) {
        while (k >= 2u && cross(hull[k - 2u], hull[k - 1u], points[i]) <= 0.0) --k;
        hull[k++] = points[i];
    }
    for (std::size_t i = points.size() - 1u, floor = k + 1u; i > 0; --i) {
        while (k >= floor && cross(hull[k - 2u], hull[k - 1u], points[i - 1u]) <= 0.0) --k;
        hull[k++] = points[i - 1u];
    }
    hull.resize(k - 1u);
    double twice = 0.0;
    for (std::size_t i = 0; i < hull.size(); ++i) {
        const std::array<double, 2>& u = hull[i];
        const std::array<double, 2>& v = hull[(i + 1u) % hull.size()];
        twice += u[0] * v[1] - v[0] * u[1];
    }
    return std::fabs(twice) * 0.5;
}

/// The keys the default table drops at the first simplified level
[[nodiscard]] std::vector<MaterialKey> first_drops() {
    std::vector<MaterialKey> keys;
    for (const DetailDrop& drop : default_facade_detail_drops()) {
        if (drop.from_ratio == 0u) {
            keys.push_back(drop.key);
        }
    }
    return keys;
}

