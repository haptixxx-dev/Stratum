/**
 * @file test_building_lod.cpp
 * @brief The per-building LOD chain: does it reduce, does it float, does it hole
 * @author Stratum Team
 * @version 0.1.0
 * @date 2026
 *
 * ================================================================================
 * WHY THESE TESTS CAN FAIL
 * ================================================================================
 *
 * A LOD chain is easy to test vacuously. "Every level has fewer triangles than the
 * last" passes for a chain that returns level 0 three times, because it does not;
 * "the bounding box is unchanged" passes for a chain that deletes every triangle
 * except the eight corners of the box. Both were written, and both were replaced.
 *
 * Every assertion here is one of six kinds, and each kind was chosen because a
 * specific plausible bug survives the other five:
 *
 *   - **A triangle multiset, not a triangle count.** Level 0 promises to carry
 *     every triangle of the input. The implementation that lost the roof -- 14 of
 *     400 triangles, the ones no SubMesh range claimed -- passed a count-based
 *     test of the ranges it did copy. It cannot pass a multiset comparison
 *     against the input.
 *
 *   - **An achieved ratio against a bound the broken behaviour misses by a
 *     mile.** The constrained simplifier stalls at 82% of level 0 on
 *     rule-generated geometry however low the ratio, so a test that accepted 85%
 *     would pass against exactly the behaviour build_building_lod() exists to
 *     beat. The bound is 0.2, and the "both mechanisms off" run is asserted to be
 *     strictly worse, so the number is a comparison this suite makes rather than
 *     a meshoptimizer constant it hard-codes.
 *
 *   - **Covered area, not triangle count, for the openings.** A window that
 *     half-collapses leaves a hole in a wall, and a hole costs triangles exactly
 *     as removing the window cleanly does. So the window tests measure the area
 *     of the opening that geometry still covers, and the suite includes the
 *     mutation that makes that number go to zero -- dropping the glazing instead
 *     of the reveal -- so the metric is known to be able to fail.
 *
 *   - **A RAY THROUGH EVERY OPENING, ON EVERY LEVEL OF A REAL CHAIN.** The kind
 *     that was missing, and the defect it was missing was a big one. The covered
 *     area above is a correct instrument and it was only ever pointed at
 *     drop_detail_keys() on a one-window fixture, so what build_building_lod()
 *     actually shipped went unmeasured -- and what it shipped had 24% of the
 *     front wall of the building see-through at its coarsest level, with all
 *     sixteen tests green over it. every_level_covers_the_openings_level_zero_
 *     covered walks every level of four configurations and counts rays. It is
 *     deliberately a DIFFERENT instrument from the one the implementation uses
 *     for the same job: the implementation shoots along each covering triangle's
 *     own normal, this walks a grid of world coordinates worked out by hand from
 *     the rule file. A test that re-ran the implementation's own measurement
 *     could only ever agree with it.
 *
 *   - **The ground plane, by position and not by bounding box.** A bounding box
 *     says nothing about whether the base ring is still the base ring. The tests
 *     compare the SET of quantised base positions across levels.
 *
 *   - **Two configurations that must disagree.** Every "the setting reached the
 *     geometry" test is a pair: with and without the ground band, with and
 *     without the detail drops, with and without the sloppy retry. A test that
 *     only ever runs the default configuration cannot tell a setting that works
 *     from a setting that is ignored.
 *
 * ### The two fixtures
 *
 * **The tower** is hand-built: a rectangular prism whose four walls are
 * subdivided 8 x 10 and a pyramid cap, welded, with real interior vertices and a
 * base ring of 32 distinct positions. It is what the ground-contact and
 * switch-distance questions are asked against, because its base ring is dense
 * enough for a simplifier to have somewhere to move it to.
 *
 * **The facade** is generated by the rule language itself -- extrude, gable roof,
 * `split` into floors and bays, `window()` in each bay -- because the quilt
 * problem this file exists for is a property of what the rule language emits and
 * a hand-built fixture would not have it. It is also the proof that E6 works on
 * E3's and E5's real output rather than on a mesh written to suit it. Its twelve
 * openings are at coordinates derived by hand from the rule text, which is what
 * makes the ray tests independent of the mesh they measure.
 *
 * ### What this suite still does not cover, stated rather than implied
 *
 * - The ONE-RING half of the lock dilation is inert on both fixtures. Removing it
 *   leaves every test here green. building_lod.cpp says so at dilate_lock_set()
 *   and gives its reasons for keeping it; this is the same fact from the suite's
 *   side.
 * - The corner samples in the implementation's own cover test are inert for the
 *   same reason: every failure either fixture produces opens a whole pane rather
 *   than half of one.
 *
 * Neither is a hole in a test. Both are code that no fixture here can distinguish
 * from its absence, recorded so that a green run is not read as covering them.
 *
 * Run just this suite with:
 * @code
 *     ./stratum_tests BuildingLod
 * @endcode
 */

